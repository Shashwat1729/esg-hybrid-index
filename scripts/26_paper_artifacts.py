def weight_table(M):
    profiles = {p: load_profile_weights(p) for p in ("esg_first", "balanced", "financial_first")}
    rows = ["ESG_composite", "financial_score", "risk_adjusted_score", "growth_score",
            "stability_score", "sector_position", "operational_score", "value_score", "market_score"]
    eff = {}
    for p, w in profiles.items():
        w = {k: v for k, v in w.items() if k != "similarity_rank"}
        nm = {k: v for k, v in w.items() if k != "market_score"}
        tot = sum(nm.values())
        eff[p] = {k: (v / tot if k != "market_score" else 0.0) for k, v in w.items()}
        eff[p]["_raw_market"] = w.get("market_score", 0.0)
    lines = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule",
             "Factor & ESG-first & Balanced & Financial-first \\\\", "\\midrule"]
    for k in rows:
        lines.append(f"{FACTOR_LABELS[k].replace(' (not weighted)', '')} & " +
                     " & ".join(f"{100 * eff[p].get(k, 0):.1f}" for p in profiles) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_weights.tex", "\n".join(lines) + "\n")
    M.add("WBalESG", f"{100 * eff['balanced']['ESG_composite']:.1f}")
    M.add("WESGFirstESG", f"{100 * eff['esg_first']['ESG_composite']:.1f}")
    M.add("WFinFirstESG", f"{100 * eff['financial_first']['ESG_composite']:.1f}")

    sasb = yaml.safe_load((PROJECT_ROOT / "config" / "sasb_materiality.yaml").read_text(encoding="utf-8"))
    sm = sasb["sector_materiality"]
    lines = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule", "Sector & E & S & G \\\\", "\\midrule"]
    for sec, w in sm.items():
        if sec == "default":
            continue
        lines.append(f"{sec} & {w['E']:.2f} & {w['S']:.2f} & {w['G']:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_sasb.tex", "\n".join(lines) + "\n")


