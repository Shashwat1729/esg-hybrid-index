def find_fx(cfg):
    """INR_USD may sit at top level or inside a nested block."""
    def walk(d):
        if isinstance(d, dict):
            for k, v in d.items():
                if k == "INR_USD":
                    return v
                r = walk(v)
                if r is not None:
                    return r
        return None
    return walk(cfg)


