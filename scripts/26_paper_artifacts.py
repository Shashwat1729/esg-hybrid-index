def diagnostics(M, u):
    vif = read("vif_multicollinearity.csv")
    M.add("VIFMax", float(vif["VIF"].max()), "{:.2f}")
    M.add("VIFMaxFactor", FACTOR_LABELS.get(vif.loc[vif["VIF"].idxmax(), "factor"], "").replace("\\quad ", ""))
    pre_vif = read("vif_multicollinearity.csv", PRE)
    M.add("VIFMaxPre", float(pre_vif["VIF"].max()), "{:.2f}")

    pca = read("advanced_pca_variance.csv")
    cum = pca["cumulative_variance"].to_numpy()
    M.add("PCAFirstThree", float(100 * cum[2]), "{:.1f}")
    M.add("PCANEighty", int(np.argmax(cum >= 0.80) + 1))

    mono = read("factor_monotonicity_diagnostic.csv")
    pre_mono = read("factor_monotonicity_diagnostic.csv", PRE)
    M.add("MonoPost", int(mono["is_monotonic"].astype(str).eq("True").sum()))
    M.add("MonoPre", int(pre_mono["is_monotonic"].astype(str).eq("True").sum()))
    M.add("MonoTotal", len(mono))

    prc = read("profile_rank_correlation.csv")
    def pr(a, b):
        r = prc[((prc.profile1 == a) & (prc.profile2 == b)) | ((prc.profile1 == b) & (prc.profile2 == a))]
        return float(r["spearman_rank_r"].iloc[0])
    M.add("RhoProfEB", pr("pref_esg_first", "pref_balanced"), "{:.2f}")
    M.add("RhoProfBF", pr("pref_balanced", "pref_financial_first"), "{:.2f}")
    M.add("RhoProfEF", pr("pref_esg_first", "pref_financial_first"), "{:.2f}")
    top_n = get_portfolio_top_n(len(u))
    def overlap(a, b):
        ta = set(u.nlargest(top_n, a)["ticker"])
        tb = set(u.nlargest(top_n, b)["ticker"])
        return len(ta & tb)
    M.add("OverlapEB", overlap("pref_esg_first", "pref_balanced"))
    M.add("OverlapBF", overlap("pref_balanced", "pref_financial_first"))
    M.add("OverlapEF", overlap("pref_esg_first", "pref_financial_first"))

    power = read("power_analysis.csv")
    mde = power.loc[power["test_type"] == "correlation", "min_detectable_effect"].dropna().iloc[0]
    M.add("MDEFull", float(mde), "{:.3f}")


def pre_post(M, u):
    pre = pd.read_csv(PRE / "indexed_data.csv")
    pre = pre[~pre["is_large_cap_benchmark"].fillna(False).astype(bool)]
    j = u[["ticker", "pref_balanced", "ESG_composite", "E_score", "S_score", "G_score"]].merge(
        pre[["ticker", "pref_balanced", "ESG_composite", "E_score", "S_score", "G_score"]],
        on="ticker", suffixes=("", "_pre"))
    M.add("NPrePostCommon", len(j))
    for col, nm in (("pref_balanced", "Bal"), ("ESG_composite", "ESG"), ("E_score", "E"),
                    ("S_score", "S"), ("G_score", "G")):
        M.add(f"RhoPrePost{nm}", float(stats.spearmanr(j[col], j[f"{col}_pre"])[0]), "{:.2f}")
    top_n = get_portfolio_top_n(len(u))
    top_post = set(u.nlargest(top_n, "pref_balanced")["ticker"])
    top_pre = set(pre.nlargest(top_n, "pref_balanced")["ticker"])
    M.add("OverlapPrePost", len(top_post & top_pre))

    boot = read("advanced_bootstrap_ci.csv")
    # The paper previously cited the "enhanced" (Bayesian-bootstrap) intervals.
    pre_boot = read("bootstrap_enhanced_stability.csv", PRE)
    pre_w = (pre_boot["ci_upper"] - pre_boot["ci_lower"])
    M.add("PreCIWidthMedian", float(pre_w.median()), "{:.0f}")
    M.add("PreCIWidthMin", float(pre_w.min()), "{:.0f}")
    M.add("PreNFirmsBoot", len(pre_boot))

    circ = read("circularity_comparison.csv")
    def ins(h, v):
        r = circ[(circ.horizon == h) & (circ.score_variant == v)]
        return float(r["ic_with_market"].iloc[0]) if len(r) else np.nan
    oos = read("oos_information_coefficients.csv")
    def oosic(sig, h="full"):
        r = oos[(oos.signal == sig) & (oos.horizon == h) & (oos.neutralization == "country")]
        return r.iloc[0] if len(r) else None

    lines = ["\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
             "& \\multicolumn{2}{c}{In-sample (pre-snapshot)} & \\multicolumn{2}{c}{Out-of-sample} \\\\",
             "\\cmidrule(lr){2-3}\\cmidrule(l){4-5}",
             "Composite & vs.\\ trailing 6m & vs.\\ quality proxy & IC, full window & 95\\% CI \\\\",
             "\\midrule"]
    for sig in ("pref_balanced", "pref_esg_first", "pref_financial_first"):
        o = oosic(sig)
        lines.append(" & ".join([FACTOR_LABELS[sig], fnum(ins("6m", sig)), fnum(ins("quality", sig)),
                                 fnum(o["ic"]) if o is not None else "--",
                                 f"[{fnum(o['ci_low'])}, {fnum(o['ci_high'])}]" if o is not None else "--"]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_insample_vs_oos.tex", "\n".join(lines) + "\n")
    M.add("InSampleICBalSixM", ins("6m", "pref_balanced"), "{:.2f}")
    M.add("InSampleICBalQuality", ins("quality", "pref_balanced"), "{:.2f}")

    # Pre/post audit diagnostic table
    boot_top = boot[boot["original_rank"] <= top_n]
    rows = [
        ("Factors monotonic in quintiles of the quality proxy",
         f"{M_get(M, 'MonoPre')}/{M_get(M, 'MonoTotal')}", f"{M_get(M, 'MonoPost')}/{M_get(M, 'MonoTotal')}"),
        ("Median 95\\% rank-CI width, all firms", f"{pre_w.median():.0f}", f"{boot['ci_width'].median():.0f}"),
        ("Maximum VIF among factor scores", f"{read('vif_multicollinearity.csv', PRE)['VIF'].max():.2f}",
         f"{read('vif_multicollinearity.csv')['VIF'].max():.2f}"),
        (f"Top-{top_n} balanced portfolio: firms in common", "--", f"{len(top_post & top_pre)}/{top_n}"),
        ("Balanced composite: Spearman $\\rho$ pre vs.\\ post", "--",
         f"{stats.spearmanr(j['pref_balanced'], j['pref_balanced_pre'])[0]:.2f}"),
    ]
    oo_pre = oosic("pref_balanced_pre_audit")
    oo_post = oosic("pref_balanced")
    if oo_pre is not None and oo_post is not None:
        rows.append(("Out-of-sample IC of the balanced composite", fnum(oo_pre["ic"]), fnum(oo_post["ic"])))
    lines = ["\\begin{tabular}{@{}p{0.58\\columnwidth}rr@{}}", "\\toprule",
             "Diagnostic & Pre-audit & Post-audit \\\\", "\\midrule"]
    lines += [f"{a} & {b} & {c} \\\\" for a, b, c in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_pre_post.tex", "\n".join(lines) + "\n")
    _ = boot_top


def M_get(M, name):
    for line in M.lines:
        if line.startswith(f"\\newcommand{{\\{name}}}"):
            return line.split("}{", 1)[1].rsplit("\\xspace", 1)[0]
    raise KeyError(name)


