class Macros:
    def __init__(self):
        self.lines = ["% Auto-generated by scripts/26_paper_artifacts.py -- do not edit by hand.",
                      "% Re-run `python scripts/run_all.py` (or this script) to refresh."]
        self.names = set()

    def add(self, name, value, fmt=None):
        if not name.isalpha():
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.names:
            raise ValueError(f"duplicate macro {name}")
        self.names.add(name)
        if isinstance(value, (float, np.floating)):
            text = (fmt or "{:.3f}").format(value)
            text = text.replace("-", NEG, 1) if text.startswith("-") else text
        else:
            text = str(value)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{text}\\xspace}}")

    def write(self, path):
        path.write_text("\n".join(self.lines) + "\n", encoding="utf-8")


def fnum(x, fmt="{:.3f}"):
    if pd.isna(x):
        return "--"
    s = fmt.format(x)
    return s.replace("-", NEG, 1) if s.startswith("-") else s


def pval(p):
    if pd.isna(p):
        return "--"
    if p < 0.001:
        return LT + "0.001"
    return f"{p:.3f}"


def write_table(name, body):
    (GEN / name).write_text("% Auto-generated by scripts/26_paper_artifacts.py\n" + body, encoding="utf-8")


