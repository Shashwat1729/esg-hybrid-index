def provenance(M, u):
    prov = read("esg_data_provenance.csv").set_index("ticker").reindex(u["ticker"])
    rows, used = [], {}
    for pillar, cols in (("E", ESG_ENV_COLS), ("S", ESG_SOC_COLS), ("G", ESG_GOV_COLS)):
        cells = []
        n_used = 0
        for c in cols:
            if c not in u.columns or u[c].notna().sum() == 0 or u[c].nunique() < 2:
                continue
            n_used += 1
            labels = prov[c] if c in prov.columns else pd.Series("direct_ratio", index=prov.index)
            for lab in labels.fillna("direct_ratio"):
                if lab == "real_yahoo":
                    cells.append("ISS governance score" if c in ISS_COLS else "Yahoo ownership/coverage field")
                elif lab == "real_sec":
                    cells.append("SEC XBRL item")
                elif lab == "real_public_registry":
                    cells.append("Public registry (0/1)")
                elif lab == "direct_ratio":
                    cells.append("Financial ratio")
                elif lab == "financial_proxy":
                    cells.append("Financial proxy")
                else:
                    cells.append("Imputed")
        share = pd.Series(cells).value_counts(normalize=True) * 100
        used[pillar] = n_used
        rows.append((pillar, n_used, len(cols), share))
        M.add(f"NInd{pillar}", n_used)
        M.add(f"NIndDeclared{pillar}", len(cols))
        M.add(f"ProxyShare{pillar}", float(share.get("Financial proxy", 0.0) + share.get("Financial ratio", 0.0)), "{:.0f}")
        M.add(f"ISSShare{pillar}", float(share.get("ISS governance score", 0.0)), "{:.0f}")
    M.add("NIndUsed", sum(used.values()))
    M.add("NIndDeclared", len(ESG_ENV_COLS) + len(ESG_SOC_COLS) + len(ESG_GOV_COLS))
    iss_firms = int((prov[[c for c in ISS_COLS if c in prov]] == "real_yahoo").any(axis=1).sum())
    M.add("NISSFirms", iss_firms)
    M.add("NEPAFirms", int((prov == "real_epa").any(axis=1).sum()))

    M.add("NIndUnused", len(ESG_ENV_COLS) + len(ESG_SOC_COLS) + len(ESG_GOV_COLS) - sum(used.values()))

    # Sources as rows, pillars as columns (fits a single column).
    lines = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule",
             "Source of cell & E & S & G \\\\", "\\midrule",
             "Indicators used / declared & " + " & ".join(f"{n}/{d}" for _, n, d, _ in rows) + " \\\\",
             "\\midrule"]
    for t in TIER_ORDER:
        vals = []
        for _, _, _, share in rows:
            v = share.get(t, 0.0)
            vals.append("--" if v == 0 else LT + "1" if v < 0.5 else f"{v:.0f}")
        lines.append(f"{t} & " + " & ".join(vals) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_provenance.tex", "\n".join(lines) + "\n")


def esg_redundancy(M, u):
    others = ["financial_score", "operational_score", "risk_adjusted_score", "value_score",
              "growth_score", "stability_score", "market_score"]
    X = np.column_stack([np.ones(len(u))] + [u[c].fillna(u[c].median()) for c in others])
    for col, name in (("ESG_composite", "ESG"), ("E_score", "E"), ("S_score", "S"), ("G_score", "G")):
        y = u[col].fillna(u[col].median()).to_numpy()
        b = np.linalg.lstsq(X, y, rcond=None)[0]
        r2 = 1 - np.var(y - X @ b) / np.var(y)
        M.add(f"RSq{name}", float(r2), "{:.2f}")
    rho = stats.spearmanr(u["ESG_composite"], u["financial_score"])[0]
    M.add("RhoESGFin", float(rho), "{:.2f}")
    for a, b, nm in (("E_score", "S_score", "RhoES"), ("E_score", "G_score", "RhoEG"), ("S_score", "G_score", "RhoSG")):
        M.add(nm, float(stats.spearmanr(u[a], u[b])[0]), "{:.2f}")


