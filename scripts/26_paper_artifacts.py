def rank_uncertainty(M, u):
    s = read("bootstrap_rank_uncertainty_summary.csv").iloc[0]
    M.add("BootN", int(s["n_bootstrap"]))
    M.add("BootKappa", f"{s['dirichlet_concentration']:.0f}")
    M.add("BootRecon", float(s["reconstruction_spearman"]), "{:.3f}")
    M.add("CIWidthAll", float(s["median_ci_width_all"]), "{:.0f}")
    M.add("CIWidthTop", float(s["median_ci_width_top_n"]), "{:.0f}")
    M.add("CIWidthTopMax", float(s["max_ci_width_top_n"]), "{:.0f}")
    M.add("CIWidthTopSampling", float(s["median_ci_width_sampling_top_n"]), "{:.0f}")
    M.add("CIWidthTopWeights", float(s["median_ci_width_weights_top_n"]), "{:.0f}")
    M.add("MeanPTop", float(s["mean_p_top_n_of_top_n"]), "{:.2f}")
    M.add("NPTopHalf", int(s["n_top_n_with_p_ge_0_5"]))
    M.add("ExpOverlap", float(s["expected_top_n_overlap"]), "{:.1f}")

    boot = read("advanced_bootstrap_ci.csv")
    top_n = int(s["top_n"])
    info = u.set_index("ticker")[["sector", "country"]]
    oos = read("oos_firm_outcomes.csv").set_index("ticker") if (TABLES / "oos_firm_outcomes.csv").exists() else None
    lines = ["\\begin{tabular}{@{}rllrr r@{}}", "\\toprule",
             "Rank & Ticker & Sector & 95\\% CI & $P(\\text{top-}N)$ & OOS ret.\\ (\\%) \\\\", "\\midrule"]
    for _, r in boot[boot["original_rank"] <= top_n].sort_values("original_rank").iterrows():
        t = r["ticker"]
        sec = info.loc[t, "sector"] if t in info.index else ""
        ret = oos.loc[t, "ret_full"] if oos is not None and t in oos.index else np.nan
        tick = t.replace(".NS", "$^{\\dagger}$").replace("&", "\\&")
        lines.append(f"{int(r['original_rank'])} & {tick} & {sec} & [{r['ci_lower_5']:.0f}, {r['ci_upper_95']:.0f}] "
                     f"& {r['p_top_n']:.2f} & {fnum(ret, '{:.1f}') if pd.notna(ret) else 'exit'} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_table("tab_top_ranks.tex", "\n".join(lines) + "\n")
    make_rank_figure(boot, top_n)


def make_rank_figure(boot, top_n):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    b = boot.sort_values("original_rank").head(2 * top_n)
    fig, ax = plt.subplots(figsize=(3.4, 3.6))
    y = np.arange(len(b))[::-1]
    ax.hlines(y, b["ci_lower_5"], b["ci_upper_95"], color="#4C72B0", lw=2)
    ax.plot(b["original_rank"], y, "o", color="black", ms=3, label="Point rank")
    ax.axvline(top_n + 0.5, color="#C44E52", ls="--", lw=1, label=f"Top-{top_n} cut-off")
    ax.set_yticks(y)
    ax.set_yticklabels([t.replace(".NS", "*") for t in b["ticker"]], fontsize=5.5)
    ax.set_xlabel("Balanced-profile rank (point and 95% interval)", fontsize=6.5)
    ax.tick_params(axis="x", labelsize=6.5)
    ax.legend(fontsize=6, loc="upper right", frameon=False)
    ax.grid(axis="x", alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_rank_ci.pdf")
    plt.close(fig)


